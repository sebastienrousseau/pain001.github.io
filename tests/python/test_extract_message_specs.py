"""Tests for scripts/extract_message_specs.py: the provenance header
read from each XSD, the named-type and inline-type schema walks (bounded
and cycle-aware), placeholder and missing schemas, the per-version JSON
files, and the cross-version index (deltas within a family only, and
code-list coverage).

Schemas are small synthetic XSDs written to ``tmp_path``, padded past
the placeholder threshold; nothing is read from a pain001 checkout.
"""

import json
import sys
import xml.etree.ElementTree as ET

import extract_message_specs as ems

PAD = "<!-- " + "x" * ems.PLACEHOLDER_MIN_BYTES + " -->\n"
XS_NS = 'xmlns:xs="http://www.w3.org/2001/XMLSchema"'

NAMED = """<?xml version="1.0" encoding="UTF-8"?>
{header}{pad}<xs:schema {ns}>
<xs:element name="Document" type="Document"/>
<xs:complexType name="Document"><xs:sequence>
<xs:element name="CstmrCdtTrfInitn" type="Initn"/></xs:sequence></xs:complexType>
<xs:complexType name="Initn"><xs:annotation><xs:documentation>Initiation
   block</xs:documentation></xs:annotation><xs:sequence>
<xs:element name="GrpHdr" type="GrpHdr"/>
<xs:element name="PmtInf" type="PmtInf" maxOccurs="unbounded"/>
</xs:sequence></xs:complexType>
<xs:complexType name="GrpHdr"><xs:sequence>{grphdr}</xs:sequence></xs:complexType>
<xs:complexType name="PmtInf"><xs:choice>
<xs:element name="Id" type="Max35Text"/><xs:element name="Pty" type="Party"/>
</xs:choice></xs:complexType>
<xs:complexType name="Party"><xs:sequence>
<xs:element name="Nm" type="Max35Text"/><xs:element name="Ownr" type="Party" minOccurs="0"/>
</xs:sequence></xs:complexType>
<xs:complexType/>
<xs:simpleType name="Max35Text"><xs:restriction base="xs:string">
<xs:minLength value="1"/><xs:maxLength value="35"/></xs:restriction></xs:simpleType>
<xs:simpleType name="ChargeBearer"><xs:annotation><xs:documentation>Who pays</xs:documentation></xs:annotation>
<xs:restriction base="xs:string"><xs:enumeration value="DEBT"/><xs:enumeration value="CRED"/>
</xs:restriction></xs:simpleType>
<xs:simpleType name="Tokens"><xs:list itemType="xs:string"/></xs:simpleType>
<xs:simpleType/>
</xs:schema>
"""

MSGID = ('<xs:element name="MsgId" type="Max35Text"><xs:annotation><xs:documentation>Point to point\n'
         " reference.</xs:documentation></xs:annotation></xs:element>")
CHRGBR = '<xs:element name="ChrgBr" type="ChargeBearer" minOccurs="0"/>'
CREDTTM = '<xs:element name="CreDtTm" type="xs:dateTime"/>'

INLINE = """<?xml version="1.0"?>
{pad}<xs:schema {ns}>
<xs:element name="Document"><xs:complexType><xs:sequence>
<xs:element name="CstmrDrctDbtInitn"><xs:complexType><xs:choice>
<xs:element name="GrpHdr" minOccurs="0"><xs:annotation><xs:documentation>Header</xs:documentation>
</xs:annotation><xs:complexType><xs:all/></xs:complexType></xs:element>
<xs:element name="SeqTp" type="SeqType" maxOccurs="2"><xs:simpleType><xs:restriction base="xs:string">
<xs:enumeration value="FRST"/><xs:enumeration value="RCUR"/></xs:restriction></xs:simpleType></xs:element>
<xs:element ref="Other"/>
</xs:choice></xs:complexType></xs:element>
</xs:sequence></xs:complexType></xs:element>
</xs:schema>
"""

NO_ROOT = '<?xml version="1.0"?>\n{pad}<xs:schema {ns}><xs:simpleType name="Lone"/></xs:schema>\n'


def _xsd(templates, version, text):
    folder = templates / version
    folder.mkdir(parents=True)
    path = folder / f"{version}.xsd"
    path.write_text(text, encoding="utf-8")
    return path


def _library(tmp_path):
    templates = tmp_path / "lib" / "pain001" / "templates"
    header03 = "<!--Generated by Standards Editor (build:R1.6.16) on 2009 May 12 10:20:00-->\n"
    _xsd(templates, "pain.001.001.03", NAMED.format(header=header03, pad=PAD, ns=XS_NS, grphdr=MSGID + CHRGBR))
    header09 = "<!--Generated by Editor on 2019 Mar 1 08:00:00-->\n"
    _xsd(templates, "pain.001.001.09", NAMED.format(header=header09, pad=PAD, ns=XS_NS, grphdr=MSGID + CREDTTM))
    _xsd(templates, "pain.001.001.01", "<xs:schema/>")
    (templates / "pain.001.001.02").mkdir()
    _xsd(templates, "pain.008.001.02", INLINE.format(pad=PAD, ns=XS_NS))
    _xsd(templates, "pain.008.001.03", NO_ROOT.format(pad=PAD, ns=XS_NS))
    return tmp_path / "lib"


def test_provenance_with_and_without_build_and_without_header(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    assert ems.schema_provenance(lib / "pain.001.001.03" / "pain.001.001.03.xsd") == {
        "generator": "Standards Editor",
        "build": "R1.6.16",
        "generated": "2009 May 12",
        "header": "Generated by Standards Editor (build:R1.6.16) on 2009 May 12",
    }
    assert ems.schema_provenance(lib / "pain.001.001.09" / "pain.001.001.09.xsd")["build"] is None
    assert ems.schema_provenance(lib / "pain.008.001.02" / "pain.008.001.02.xsd") == {
        "generator": None, "build": None, "generated": None, "header": None}


def test_parse_schema_reads_root_and_complex_types(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    model = ems.parse_schema(lib / "pain.001.001.03" / "pain.001.001.03.xsd")
    assert model["root_element"] == "Document" and model["root_type"] == "Document"
    assert sorted(model["complex_types"]) == ["Document", "GrpHdr", "Initn", "Party", "PmtInf"]
    assert model["complex_types"]["Initn"]["doc"] == "Initiation block"
    assert model["complex_types"]["PmtInf"]["kind"] == "choice"
    assert model["complex_types"]["GrpHdr"]["children"][0] == {
        "name": "MsgId", "type": "Max35Text", "min": "1", "max": "1", "doc": "Point to point reference."}


def test_parse_schema_reads_simple_types_facets_and_codes(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    simple = ems.parse_schema(lib / "pain.001.001.03" / "pain.001.001.03.xsd")["simple_types"]
    assert sorted(simple) == ["ChargeBearer", "Max35Text", "Tokens"]
    assert simple["Max35Text"]["facets"] == {"minLength": "1", "maxLength": "35"}
    assert simple["ChargeBearer"]["codes"] == ["DEBT", "CRED"]
    assert simple["ChargeBearer"]["doc"] == "Who pays"
    assert simple["Tokens"] == {"name": "Tokens", "base": None, "codes": [], "facets": {}, "doc": ""}


def test_parse_schema_without_a_root_element(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    model = ems.parse_schema(lib / "pain.008.001.03" / "pain.008.001.03.xsd")
    assert model["root_element"] is None and model["root_type"] is None


def test_walk_is_bounded_and_stops_at_cycles(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    model = ems.parse_schema(lib / "pain.001.001.03" / "pain.001.001.03.xsd")
    rows = ems.walk(model, "Document")
    assert [r["path"] for r in rows] == [
        "CstmrCdtTrfInitn",
        "CstmrCdtTrfInitn/GrpHdr",
        "CstmrCdtTrfInitn/GrpHdr/MsgId",
        "CstmrCdtTrfInitn/GrpHdr/ChrgBr",
        "CstmrCdtTrfInitn/PmtInf",
        "CstmrCdtTrfInitn/PmtInf/Id",
        "CstmrCdtTrfInitn/PmtInf/Pty",
        "CstmrCdtTrfInitn/PmtInf/Pty/Nm",
        "CstmrCdtTrfInitn/PmtInf/Pty/Ownr",
    ]
    chrgbr = rows[3]
    assert chrgbr["codes"] == ["DEBT", "CRED"] and chrgbr["min"] == "0" and chrgbr["depth"] == 2
    assert rows[5]["in_choice"] is True and rows[5]["facets"] == {"minLength": "1", "maxLength": "35"}
    assert rows[1]["codes"] == [] and rows[1]["facets"] == {}
    assert ems.walk(model, "Document", max_depth=-1) == []
    assert ems.walk(model, "Max35Text") == []
    assert len(ems.walk(model, "Document", max_depth=1)) == 3


def test_walk_inline_handles_choice_leaves_refs_and_depth(tmp_path):
    lib = _library(tmp_path) / "pain001" / "templates"
    root = ET.parse(lib / "pain.008.001.02" / "pain.008.001.02.xsd").getroot().find(f"{ems.XS}element")
    rows = ems.walk_inline(root)
    assert [(r["path"], r["type"], r["in_choice"], r["depth"]) for r in rows] == [
        ("CstmrDrctDbtInitn", "(inline)", False, 0),
        ("CstmrDrctDbtInitn/GrpHdr", "(inline)", True, 1),
        ("CstmrDrctDbtInitn/SeqTp", "SeqType", True, 1),
    ]
    assert rows[1]["doc"] == "Header" and rows[1]["min"] == "0"
    assert rows[2]["codes"] == ["FRST", "RCUR"] and rows[2]["max"] == "2"
    assert ems.walk_inline(root, depth=7) == []


def test_main_without_templates_fails(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(sys, "argv", ["extract_message_specs.py", str(tmp_path / "nowhere")])
    assert ems.main() == 1
    assert f"library templates not found at {tmp_path / 'nowhere' / 'pain001' / 'templates'}" in capsys.readouterr().err


def _run_main(tmp_path, monkeypatch):
    out = tmp_path / "message_specs"
    monkeypatch.setattr(ems, "OUT", out)
    monkeypatch.setattr(ems, "DEFAULT_LIB", _library(tmp_path))
    monkeypatch.setattr(sys, "argv", ["extract_message_specs.py"])
    assert ems.main() == 0
    return out


def test_main_writes_each_version_and_the_index(tmp_path, monkeypatch, capsys):
    out = _run_main(tmp_path, monkeypatch)
    assert sorted(p.name for p in out.iterdir()) == [
        "index.json", "pain.001.001.03.json", "pain.001.001.09.json",
        "pain.008.001.02.json", "pain.008.001.03.json"]
    printed = capsys.readouterr().out
    assert "pain.001.001.03: 9 element rows, 5 types, 1 code lists" in printed
    assert "indexed 4 version(s); skipped placeholders: ['pain.001.001.01']" in printed


def test_main_writes_the_named_type_version(tmp_path, monkeypatch):
    out = _run_main(tmp_path, monkeypatch)
    v03 = json.loads((out / "pain.001.001.03.json").read_text(encoding="utf-8"))
    assert v03["element_count"] == 9 and v03["complex_type_count"] == 5 and v03["code_list_count"] == 1
    assert v03["provenance"]["build"] == "R1.6.16"
    assert list(v03["code_lists"]) == ["ChargeBearer"]
    grphdr = v03["type_index"]["GrpHdr"]
    assert grphdr["kind"] == "sequence"
    assert grphdr["children"][1] == {"name": "ChrgBr", "type": "ChargeBearer", "min": "0", "max": "1",
                                     "codes": ["DEBT", "CRED"], "facets": {}}
    assert v03["type_index"]["Party"]["children"][1]["codes"] == []


def test_main_writes_the_inline_and_rootless_versions(tmp_path, monkeypatch):
    out = _run_main(tmp_path, monkeypatch)
    inline = json.loads((out / "pain.008.001.02.json").read_text(encoding="utf-8"))
    assert inline["element_count"] == 3 and inline["root_element"] == "Document"
    assert json.loads((out / "pain.008.001.03.json").read_text(encoding="utf-8"))["element_count"] == 0


def test_index_diffs_within_a_family_and_records_code_list_coverage(tmp_path, monkeypatch):
    out = _run_main(tmp_path, monkeypatch)
    index = json.loads((out / "index.json").read_text(encoding="utf-8"))
    assert index["versions"] == ["pain.001.001.03", "pain.001.001.09", "pain.008.001.02", "pain.008.001.03"]
    assert index["skipped"] == ["pain.001.001.01"]
    assert index["deltas"] == {
        "pain.001.001.03->pain.001.001.09": {
            "added": ["CstmrCdtTrfInitn/GrpHdr/CreDtTm"],
            "removed": ["CstmrCdtTrfInitn/GrpHdr/ChrgBr"],
        },
        "pain.008.001.02->pain.008.001.03": {
            "added": [],
            "removed": ["CstmrDrctDbtInitn", "CstmrDrctDbtInitn/GrpHdr", "CstmrDrctDbtInitn/SeqTp"],
        },
    }
    assert index["code_list_coverage"] == {
        "ChargeBearer": {"versions": ["pain.001.001.03", "pain.001.001.09"], "codes": ["DEBT", "CRED"]}}


def test_no_versions_reports_none_skipped(tmp_path, monkeypatch, capsys):
    (tmp_path / "lib" / "pain001" / "templates").mkdir(parents=True)
    monkeypatch.setattr(ems, "OUT", tmp_path / "message_specs")
    monkeypatch.setattr(sys, "argv", ["extract_message_specs.py", str(tmp_path / "lib")])
    assert ems.main() == 0
    index = json.loads((tmp_path / "message_specs" / "index.json").read_text(encoding="utf-8"))
    assert index == {"versions": [], "skipped": [], "deltas": {}, "code_list_coverage": {}}
    assert "indexed 0 version(s); skipped placeholders: none" in capsys.readouterr().out
