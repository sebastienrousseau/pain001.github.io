"""Tests for scripts/generate_message_specs.py, part 1: the small
formatters (ISO links, provenance sentence, cardinality, constraints,
escaping), the frontmatter cloned from a template post, and the hub,
code-list and changes pages. Part 2 covers the per-version pages, the
type reference and main().

Every page is written to a ``tmp_path`` posts directory from a minimal
template post; nothing reads or writes the repository's ``_posts``.
"""

import re

import pytest

import generate_message_specs as gms

TEMPLATE = """---
author: "someone"
title: "FAQs"
description: "Old description"
twitter_title: "Old"
id: "https://pain001.com/faqs/"
permalink: "https://pain001.com/faqs/"
item_link: https://elsewhere.example/
---

Body of the template post.
"""


@pytest.fixture
def posts(tmp_path, monkeypatch):
    folder = tmp_path / "_posts"
    folder.mkdir()
    (folder / "faqs.md").write_text(TEMPLATE, encoding="utf-8")
    monkeypatch.setattr(gms, "POSTS", folder)
    monkeypatch.setattr(gms, "TEMPLATE_POST", folder / "faqs.md")
    monkeypatch.setattr(gms, "CURRENT_VERSIONS", {"pain.001.001.12"})
    return folder


def _front(text):
    return dict(re.findall(r'^([\w-]+): (.*)$', text.split("\n---\n", 1)[0][4:], re.M))


def test_iso_link_points_current_versions_at_the_catalogue():
    assert gms.iso_link("pain.001.001.12", {"pain.001.001.12"}) == (
        "[ISO 20022 catalogue](https://www.iso20022.org/iso-20022-message-definitions?search=pain.001.001.12)")
    assert gms.iso_link("pain.001.001.03", {"pain.001.001.12"}) == (
        "[ISO 20022 archive](https://www.iso20022.org/catalogue-messages/"
        "iso-20022-messages-archive?search=pain.001.001.03)")


def test_provenance_line_quotes_the_header_or_says_there_is_none():
    named = gms.provenance_line(
        {"version": "v1", "provenance": {"generated": "2026 Mar 2", "generator": "SE"}}, set())
    assert "*“Generated by SE on 2026 Mar 2”*" in named and "[ISO 20022 archive]" in named
    unnamed = gms.provenance_line({"version": "v1", "provenance": {"generated": "2026 Mar 2"}}, {"v1"})
    assert "Generated by the ISO Standards Editor on 2026 Mar 2" in unnamed
    assert "[ISO 20022 catalogue]" in unnamed
    for payload in ({"version": "v1", "provenance": None}, {"version": "v1"}):
        assert "carries **no generation header**" in gms.provenance_line(payload, set())


def test_esc_and_card():
    assert gms.esc("a|b") == "a\\|b"
    assert gms.esc(None) == ""
    assert gms.card({"min": "1", "max": "unbounded"}) == "**1..***"
    assert gms.card({"min": "0", "max": "1"}) == "0..1"
    assert gms.card({"min": "1", "max": "1"}) == "**1..1**"


def test_constraint_lists_every_facet_it_knows():
    row = {"codes": ["A", "B"], "facets": {
        "minLength": "2", "maxLength": "35", "pattern": "[A-Z]{6}" * 6,
        "fractionDigits": "5", "minInclusive": "0"}}
    assert gms.constraint(row) == (
        "2 codes; length 2–35; pattern `" + ("[A-Z]{6}" * 6)[:40] + "…`; 5 decimals max; min 0")
    assert gms.constraint({"facets": {"maxLength": "4", "pattern": "[0-9]+"}}) == "length 1–4; pattern `[0-9]+`"
    assert gms.constraint({"facets": None}) == ""
    assert gms.constraint({}) == ""


def test_frontmatter_retargets_known_keys_and_appends_missing_ones(posts):
    fm = gms.load_frontmatter("some-slug", 'A "quoted" title', "New desc", "Eyebrow", "Deck", "k1, k2")
    assert fm.startswith("---\n") and fm.endswith("\n\n---\n\n")
    front = _front(fm)
    assert front["author"] == '"someone"'
    assert front["title"] == "\"A 'quoted' title\""
    assert front["twitter_title"] == front["item_title"] == front["apple-mobile-web-app-title"] == front["title"]
    assert front["description"] == front["twitter_description"] == front["item_description"] == '"New desc"'
    assert front["subtitle"] == '"Deck"' and front["layout"] == '"page"' and front["logo_alt"] == '"Pain001 Logo"'
    assert front["id"] == front["permalink"] == '"https://pain001.com/some-slug/"'
    assert front["item_link"] == "https://elsewhere.example/"
    assert "url" not in front and "Body of the template" not in fm


def test_write_post_strips_and_ends_with_one_newline(posts):
    gms.write_post("x", "---\nfm\n---\n\n", "\n\nbody\n\n\n")
    assert (posts / "x.md").read_text(encoding="utf-8") == "---\nfm\n---\n\nbody\n"


def test_code_lists_page_lists_every_value_and_version(posts):
    index = {"versions": ["a", "b", "c"], "code_list_coverage": {
        "Zeta": {"codes": ["Z1"], "versions": ["c"]},
        "Alpha": {"codes": ["DEBT", "CRED"], "versions": ["a", "b"]},
    }}
    gms.render_code_lists({}, index)
    text = (posts / "message-spec-code-lists.md").read_text(encoding="utf-8")
    assert "**2 code lists** across 3 message versions." in text
    assert text.index("## `Alpha`") < text.index("## `Zeta`")
    assert "*2 values · in 2 version(s)*" in text
    assert "`DEBT` · `CRED`" in text and "*Appears in: `a`, `b`*" in text
    assert _front(text)["permalink"] == '"https://pain001.com/message-spec-code-lists/"'


def test_changes_page_caps_long_lists_and_names_empty_deltas(posts):
    added = [f"A/p{i:03}" for i in range(125)]
    index = {"deltas": {
        "v1->v2": {"added": added, "removed": ["R/gone"]},
        "v2->v3": {"added": [], "removed": []},
        "v3->v4": {"added": ["A/only"], "removed": []},
    }}
    gms.render_changes(index)
    text = (posts / "message-spec-changes.md").read_text(encoding="utf-8")
    first = text[text.index("## v1 → v2"):text.index("## v2 → v3")]
    assert "**125 added · 1 removed**" in first
    assert "- `A/p119`" in first and "- `A/p120`" not in first
    assert "- *…and 5 more*" in first
    assert "### Removed\n\n- `R/gone`" in first
    second = text[text.index("## v2 → v3"):text.index("## v3 → v4")]
    assert "No element-level changes" in second and "### Added" not in second
    third = text[text.index("## v3 → v4"):]
    assert "- `A/only`" in third and "### Removed" not in third and "more*" not in third


def _spec(version, elements, provenance=None):
    return {"version": version, "elements": elements, "element_count": len(elements),
            "complex_type_count": 2, "code_list_count": 1, "provenance": provenance}


def test_hub_lists_each_version_and_the_placeholders(posts):
    specs = {
        "pain.001.001.03": _spec("pain.001.001.03", [{"min": "1"}, {"min": "0"}]),
        "pain.001.001.12": _spec("pain.001.001.12", [{"min": "1"}], {"generated": "2024 Jan 5"}),
    }
    gms.render_hub(specs, {"versions": list(specs), "skipped": ["pain.001.001.01"]})
    text = (posts / "message-specs.md").read_text(encoding="utf-8")
    assert "| `pain.001.001.03` | 2 | 1 | 2 | 1 | *no header* | [ISO 20022 archive]" in text
    assert "| `pain.001.001.12` | 1 | 1 | 2 | 1 | 2024 Jan 5 | [ISO 20022 catalogue]" in text
    assert "[Element reference](/message-spec-pain.001.001.12/)" in text
    assert "### Not covered\n\n- **`pain.001.001.01`**: Pain001 ships a placeholder" in text
    assert _front(text)["id"] == '"https://pain001.com/message-specs/"'


def test_hub_without_placeholders_has_no_not_covered_section(posts):
    gms.render_hub({}, {"versions": [], "skipped": []})
    text = (posts / "message-specs.md").read_text(encoding="utf-8")
    assert "### Not covered" not in text and "## Scope and honesty" in text
