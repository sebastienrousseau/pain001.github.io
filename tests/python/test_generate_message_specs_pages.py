"""Tests for scripts/generate_message_specs.py, part 2: the per-version
element reference (block grouping, depth cut-off, type and code-list
sections, pain.001 versus other families), the single-page and chunked
type references, and main() rendering every page from the extracted
JSON with the newest version of each family marked current.

Pages are written to a ``tmp_path`` posts directory from a minimal
template post, and main() reads JSON written to ``tmp_path``.
"""

import json

import pytest

import generate_message_specs as gms

TEMPLATE = '---\ntitle: "T"\npermalink: "https://pain001.com/t/"\n---\n\nBody.\n'


@pytest.fixture
def posts(tmp_path, monkeypatch):
    folder = tmp_path / "_posts"
    folder.mkdir()
    (folder / "faqs.md").write_text(TEMPLATE, encoding="utf-8")
    monkeypatch.setattr(gms, "POSTS", folder)
    monkeypatch.setattr(gms, "TEMPLATE_POST", folder / "faqs.md")
    monkeypatch.setattr(gms, "CURRENT_VERSIONS", set())
    return folder


def _row(path, depth, minimum="1", **extra):
    return {"path": path, "name": path.rsplit("/", 1)[-1], "type": extra.pop("type", "Max35Text"),
            "min": minimum, "max": "1", "depth": depth, "codes": [], "facets": {}, **extra}


def _type(kind="sequence", *children):
    return {"kind": kind, "children": [
        {"name": c, "type": "T|x", "min": "0", "max": "unbounded", "codes": [], "facets": {}} for c in children]}


def _payload(version, **over):
    rows = [
        _row("Doc", 0),
        _row("Doc/GrpHdr", 1),
        _row("Doc/GrpHdr/MsgId", 2, facets={"maxLength": "35"}),
        _row("Doc/PmtInf", 1, "0"),
        _row("Doc/PmtInf/A/B/Deep", 4),
        _row("Doc/Custom", 1, codes=["X"]),
    ]
    payload = {
        "version": version, "elements": rows, "element_count": len(rows), "complex_type_count": 3, "code_list_count": 2,
        "provenance": None,
        "type_index": {"GrpHdr": _type("sequence", "MsgId"), "Empty": _type()},
        "code_lists": {"Many": {"codes": [f"C{i:02}" for i in range(16)]}, "Few": {"codes": ["A", "B"]}},
    }
    payload.update(over)
    return payload


def _v9_page(posts):
    gms.render_version(_payload("pain.001.001.09"), {})
    return (posts / "message-spec-pain.001.001.09.md").read_text(encoding="utf-8")


def test_version_page_groups_blocks(posts):
    text = _v9_page(posts)
    assert "**6 elements** · **5 required** · **3 types** · **2 code lists**" in text
    assert "carries **no generation header**" in text and "[ISO 20022 archive]" in text
    assert "## Doc\n\n| Element |" in text
    assert "## GrpHdr\n\n*Group Header, one per message*\n\n| Element |" in text
    assert "## Custom\n\n| Element |" in text


def test_version_page_cuts_off_deep_rows(posts):
    text = _v9_page(posts)
    assert "| &nbsp;&nbsp;&nbsp;&nbsp;`MsgId` | `Doc/GrpHdr/MsgId` | **1..1** | `Max35Text` | length 1–35 |" in text
    assert "| &nbsp;&nbsp;`PmtInf` | `Doc/PmtInf` | 0..1 |" in text
    assert "`Deep`" not in text
    assert "*1 further nested elements sit below this depth." in text
    assert text.count("further nested elements") == 1


def test_version_page_lists_types_codes_and_links(posts):
    text = _v9_page(posts)
    assert "[**pain.001.001.09 type reference**](/message-spec-pain.001.001.09-types/), 1 types in all." in text
    assert text.index("| `Few` | `A`, `B` |") < text.index("| `Many` |")
    assert "| `Many` | `C00`" in text and "`C13` *(+2 more)* |" in text and "`C14`" not in text
    assert "pain001 -t pain.001.001.09 -d payments.csv -o out/ --dry-run" in text
    assert "[narrative page for pain.001.001.09](/pain.001.001.09/)" in text
    assert 'title: "pain.001.001.09: complete element reference"' in text
    assert 'permalink: "https://pain001.com/message-spec-pain.001.001.09/"' in text


def test_version_page_for_another_family_without_types_or_codes(posts):
    gms.CURRENT_VERSIONS.add("pain.008.001.02")
    payload = _payload("pain.008.001.02", type_index=None, code_lists={},
                       provenance={"generated": "2009 May 1", "generator": "SE"})
    payload["elements"] = [_row("Solo", 0, "0")]
    gms.render_version(payload, {})
    text = (posts / "message-spec-pain.008.001.02.md").read_text(encoding="utf-8")
    assert "## Solo\n\n| Element |" in text and "| `Solo` | `Solo` | 0..1 |" in text
    assert "further nested" not in text
    assert "## Type reference" not in text and "## Code lists used" not in text
    assert "*“Generated by SE on 2009 May 1”*" in text and "[ISO 20022 catalogue]" in text
    assert "See the [compatibility matrix](/compatibility/) for supported input formats" in text
    assert "narrative page" not in text


def test_single_page_type_reference(posts):
    payload = _payload("v9", type_index={"Zed": _type("choice", "One", "Two"), "Abc": _type("sequence", "X"),
                                         "Nil": _type()})
    gms.render_types(payload)
    text = (posts / "message-spec-v9-types.md").read_text(encoding="utf-8")
    assert "**2 types.**" in text
    assert text.index("## `Abc`\n") < text.index("## `Zed` *(choice: supply one)*")
    assert "| `One` | 0..* | `T\\|x` |  |" in text
    assert "`Nil`" not in text
    assert 'permalink: "https://pain001.com/message-spec-v9-types/"' in text


def test_single_page_type_reference_skips_a_version_without_types(posts):
    assert gms.render_types(_payload("v0", type_index={"Nil": _type()})) is None
    assert gms.render_types(_payload("v0", type_index=None)) is None
    assert sorted(p.name for p in posts.iterdir()) == ["faqs.md"]


def _render_chunked_v7():
    names = [f"T{i:03}" for i in range(gms.TYPES_PER_PAGE + 2)]
    index = {n: _type("choice" if n == "T035" else "sequence", "C") for n in names}
    return gms.render_types_chunked(_payload("v7", type_index=index))


def test_chunked_type_reference_splits_at_the_page_budget(posts):
    slugs = _render_chunked_v7()
    assert slugs == ["message-spec-v7-types", "message-spec-v7-types-2"]
    first = (posts / "message-spec-v7-types.md").read_text(encoding="utf-8")
    assert "**Part 1 of 2**: `T000 – T033`." in first
    assert "**Part 1** · [Part 2](/message-spec-v7-types-2/)" in first
    assert first.count("\n## `") == gms.TYPES_PER_PAGE
    assert 'title: "v7 type reference (part 1 of 2)"' in first


def test_chunked_type_reference_writes_the_second_part(posts):
    _render_chunked_v7()
    second = (posts / "message-spec-v7-types-2.md").read_text(encoding="utf-8")
    assert "**Part 2 of 2**: `T034 – T035`." in second
    assert "[Part 1](/message-spec-v7-types/) · **Part 2**" in second
    assert "## `T035` *(choice: supply one)*" in second and "## `T034`\n" in second


def test_chunked_type_reference_on_one_page_has_no_nav(posts):
    assert gms.render_types_chunked(_payload("v8")) == ["message-spec-v8-types"]
    text = (posts / "message-spec-v8-types.md").read_text(encoding="utf-8")
    assert "**Part 1 of 1**: `GrpHdr – GrpHdr`." in text and "[Part" not in text
    assert 'title: "v8 type reference"' in text


def test_chunked_type_reference_without_types_writes_nothing(posts):
    assert gms.render_types_chunked(_payload("v0", type_index=None)) == []
    assert gms.render_types_chunked(_payload("v0", type_index={"Nil": _type()})) == []
    assert sorted(p.name for p in posts.iterdir()) == ["faqs.md"]


def _expected_pages(versions):
    """Every version page and type reference, plus the three hub pages."""
    pages = {f"message-spec-{v}{suffix}.md" for v in versions for suffix in ("", "-types")}
    return pages | {"message-specs.md", "message-spec-code-lists.md", "message-spec-changes.md"}


def test_main_renders_every_page_and_marks_the_newest_per_family(tmp_path, posts, monkeypatch, capsys):
    data = tmp_path / "message_specs"
    data.mkdir()
    versions = ["pain.001.001.03", "pain.001.001.09", "pain.008.001.02"]
    for v in versions:
        (data / f"{v}.json").write_text(json.dumps(_payload(v)), encoding="utf-8")
    index = {"versions": versions, "skipped": [], "deltas": {"pain.001.001.03->pain.001.001.09":
             {"added": ["X"], "removed": []}}, "code_list_coverage": {"Few": {"codes": ["A"], "versions": versions}}}
    (data / "index.json").write_text(json.dumps(index), encoding="utf-8")
    monkeypatch.setattr(gms, "DATA", data)

    assert gms.main() == 0

    assert gms.CURRENT_VERSIONS == {"pain.001.001.09", "pain.008.001.02"}
    written = {p.name for p in posts.iterdir()}
    assert _expected_pages(versions) - written == set()
    hub = (posts / "message-specs.md").read_text(encoding="utf-8")
    assert "| `pain.001.001.03` | 6 | 5 | 3 | 2 | *no header* | [ISO 20022 archive]" in hub
    assert "| `pain.001.001.09` | 6 | 5 | 3 | 2 | *no header* | [ISO 20022 catalogue]" in hub
    assert capsys.readouterr().out == "rendered 3 version pages + hub, code lists, changes\n"
